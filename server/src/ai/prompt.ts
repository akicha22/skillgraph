/**
 * Prompt construction for assessment wording.
 *
 * The model is asked for wording only. Facts, datasets, marks, durations, rubrics
 * and answer keys stay in code (see assessments/assembler.ts and dataTasks.ts).
 */

export type WordingPromptSkill = {
  skillSlug: string;
  name: string;
  weight: number;
  subskills: string[];
};

export type WordingPromptTask = {
  skillSlug: string;
  type: string;
  title: string;
  prompt: string;
  marks: number;
  timeMinutes: number;
};

export type WordingPromptInput = {
  requirementsText: string;
  jobTitle: string;
  companyName: string;
  description?: string;
  targetLevel: string;
  difficulty: string;
  durationMinutes: number;
  taskCount: number;
  aiPolicy: string;
  skills: WordingPromptSkill[];
  tasks: WordingPromptTask[];
};

const MAX_TASK_EXCERPT = 1200;

// Kept in sync with draftWordingSchema by ai.test.ts.
export const WORDING_CONTRACT = `{
  "title": string,                 // 5-150 characters: the assessment name
  "description": string,           // 10-600 characters: 1-2 sentences for the recruiter's library
  "jobContext": string,            // 10-1200 characters: the workplace context shown to candidates
  "candidateInstructions": string, // 20-2000 characters: how to attempt the tasks, what to submit, what is not allowed
  "tasks": [
    {
      "skillSlug": string,         // must be exactly one of the skill slugs listed in the request
      "title": string,             // optional, 5-120 characters: a clearer task title
      "brief": string              // 20-400 characters: 1-2 sentences of framing placed before the existing task text
    }
  ]
}`;

export const WORDING_SYSTEM_PROMPT = `You write candidate-facing wording for SkillGraph practical assessments.

Rules:
- You write wording only. The application owns facts, numbers, names, dates, amounts, units, marks, time limits, datasets, answer keys and rubrics. Never invent, add or change them.
- Keep every fact that already appears in a task's text. A brief introduces or frames the work; it must never contradict, replace or restate the numbers.
- Do not add new requirements, tools, deliverables, hidden criteria or questions.
- Match the stated role, seniority level and difficulty. Use plain, professional Indian English.
- Never address the candidate by name and never ask for personal or demographic information.
- If the AI assistance policy forbids AI during the assessment, say so plainly in candidateInstructions. If AI is allowed, say it must be disclosed.
- Plain prose only: no markdown headings, no bullet lists inside briefs, no emoji.
- Do not claim the assessment was generated by AI.

Return ONE JSON object and nothing else: no markdown fences, no commentary, no trailing text.
Shape (exact field names):
${WORDING_CONTRACT}`;

function taskExcerpt(text: string): string {
  const trimmed = text.trim();
  return trimmed.length <= MAX_TASK_EXCERPT ? trimmed : `${trimmed.slice(0, MAX_TASK_EXCERPT)}…`;
}

function aiPolicyLine(aiPolicy: string): string {
  return aiPolicy === "ALLOWED_DISCLOSED"
    ? "AI assistants are allowed during the assessment, but any use must be disclosed."
    : "AI assistants are not allowed during the assessment.";
}

/**
 * Builds the system + user prompt for one assessment draft.
 * Contains no candidate data: only recruiter-provided requirements and coded task text.
 */
export function buildWordingPrompt(input: WordingPromptInput): { system: string; user: string } {
  const skills = input.skills
    .map((s) => {
      const subskills = s.subskills.length > 0 ? s.subskills.join(", ") : "none selected";
      return `- ${s.name} (slug: ${s.skillSlug}), weight ${s.weight}%, subskills: ${subskills}`;
    })
    .join("\n");

  const tasks = input.tasks
    .map(
      (t, i) =>
        `Task ${i + 1} — skill: ${t.skillSlug} — type: ${t.type} — ${t.marks} marks — ${t.timeMinutes} minutes\n` +
        `Title: ${t.title}\n` +
        `Text shown to the candidate:\n"""\n${taskExcerpt(t.prompt)}\n"""`,
    )
    .join("\n\n");

  const user = `ROLE
Job title: ${input.jobTitle}
Company: ${input.companyName}
${input.description ? `Role description: ${input.description}\n` : ""}Target candidate level: ${input.targetLevel}
Difficulty: ${input.difficulty}
Total duration: ${input.durationMinutes} minutes across ${input.taskCount} task(s)
AI assistance policy: ${aiPolicyLine(input.aiPolicy)}

RECRUITER'S OWN DESCRIPTION OF THE IDEAL CANDIDATE
"""
${input.requirementsText.trim()}
"""

SELECTED SKILLS (skills and weights are fixed by the application)
${skills}

CURRENT TASK OUTLINE (this text is the source of truth for facts)
${tasks}

Write the assessment wording now. Return one "tasks" entry for every skill slug listed above.`;

  return { system: WORDING_SYSTEM_PROMPT, user };
}

